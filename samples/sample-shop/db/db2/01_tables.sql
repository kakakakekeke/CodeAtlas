-- =====================================================================
-- 배치/정산 테이블 DDL (DB2 LUW)
--   정산과 배치 로그는 DB2 에 있다. 주문/회원 테이블은 Oracle DDL 을 본다.
-- =====================================================================

-- 배치 로그 (IDENTITY 컬럼, 테이블스페이스 절)
CREATE TABLE BATCH.TB_BATCH_LOG (
    LOG_ID   BIGINT        NOT NULL GENERATED ALWAYS AS IDENTITY (START WITH 1, INCREMENT BY 1),
    JOB_NM   VARCHAR(100)  NOT NULL,
    STEP_NM  VARCHAR(100),
    STATUS   CHAR(2)       NOT NULL WITH DEFAULT 'OK',
    MSG      VARCHAR(1000),
    REG_TS   TIMESTAMP     NOT NULL WITH DEFAULT CURRENT TIMESTAMP,
    PRIMARY KEY (LOG_ID)
) IN TS_BATCH_DATA INDEX IN TS_BATCH_IDX;

-- 월 정산 (TB_MEMBER 와의 관계는 FK 제약 없이 조인으로만 알 수 있다)
CREATE TABLE TB_SETTLE (
    SETTLE_ID   BIGINT         NOT NULL,
    SETTLE_YM   CHAR(6)        NOT NULL,
    MEMBER_ID   DECIMAL(12,0)  NOT NULL,
    ORDER_CNT   INTEGER        NOT NULL WITH DEFAULT 0,
    SETTLE_AMT  DECIMAL(15,2)  NOT NULL WITH DEFAULT 0,
    REG_TS      TIMESTAMP      NOT NULL WITH DEFAULT CURRENT TIMESTAMP,
    UPD_TS      TIMESTAMP,
    CONSTRAINT PK_SETTLE PRIMARY KEY (SETTLE_ID)
) IN TS_SETTLE_DATA COMPRESS YES;

-- 월 정산 상세 (정산 FK 는 있고, 주문 FK 는 없다)
CREATE TABLE TB_SETTLE_DTL (
    DTL_ID     BIGINT         NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    SETTLE_ID  BIGINT         NOT NULL,
    ORDER_ID   DECIMAL(12,0)  NOT NULL,
    AMT        DECIMAL(15,2)  NOT NULL WITH DEFAULT 0,
    CONSTRAINT PK_SETTLE_DTL PRIMARY KEY (DTL_ID),
    CONSTRAINT FK_SETTLE_DTL_SETTLE FOREIGN KEY (SETTLE_ID)
        REFERENCES TB_SETTLE (SETTLE_ID) ON DELETE CASCADE
) IN TS_SETTLE_DATA;

CREATE SEQUENCE SEQ_SETTLE_ID AS BIGINT START WITH 1 INCREMENT BY 1 NO CYCLE CACHE 20;

CREATE INDEX IX_SETTLE_01 ON TB_SETTLE (SETTLE_YM, MEMBER_ID);
CREATE INDEX IX_SETTLE_DTL_01 ON TB_SETTLE_DTL (ORDER_ID) ALLOW REVERSE SCANS;

COMMENT ON TABLE TB_SETTLE IS '월 정산';
COMMENT ON TABLE TB_SETTLE_DTL IS '월 정산 상세';
COMMENT ON COLUMN TB_SETTLE.SETTLE_YM IS '정산년월(YYYYMM)';
