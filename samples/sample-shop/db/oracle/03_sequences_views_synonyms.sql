CREATE SEQUENCE SEQ_MEMBER_ID     START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE SEQ_PRODUCT_ID    START WITH 1000 INCREMENT BY 1 CACHE 20;
CREATE SEQUENCE SEQ_ORDER_ID      START WITH 1 INCREMENT BY 1 NOCYCLE CACHE 20;
CREATE SEQUENCE SEQ_PAYMENT_ID    START WITH 1 INCREMENT BY 1;
CREATE SEQUENCE SEQ_DELIVERY_ID   START WITH 1 INCREMENT BY 1;
CREATE SEQUENCE SEQ_ORDER_HIST_ID START WITH 1 INCREMENT BY 1 MAXVALUE 999999999999999;

-- 주문 요약 뷰 (암묵 조인 + 스칼라 서브쿼리)
CREATE OR REPLACE VIEW VW_ORDER_SUMMARY AS
SELECT O.ORDER_ID,
       O.MEMBER_ID,
       O.ORDER_DT,
       M.MEMBER_NM,
       O.ORDER_STATUS,
       O.TOTAL_AMT,
       (SELECT COUNT(*) FROM TB_ORDER_ITEM I WHERE I.ORDER_ID = O.ORDER_ID) AS ITEM_CNT
  FROM TB_ORDER O,
       TB_MEMBER M
 WHERE O.MEMBER_ID = M.MEMBER_ID;

-- 상품 재고 뷰 (컬럼 목록 지정, (+) 아우터 조인)
CREATE OR REPLACE FORCE VIEW VW_PRODUCT_STOCK (PRODUCT_ID, PRODUCT_NM, PRICE, CATEGORY_NM, STOCK_QTY) AS
SELECT P.PRODUCT_ID,
       P.PRODUCT_NM,
       P.PRICE,
       C.CATEGORY_NM,
       NVL(S.STOCK_QTY, 0)
  FROM TB_PRODUCT P,
       TB_CATEGORY C,
       TB_STOCK S
 WHERE P.CATEGORY_ID = C.CATEGORY_ID
   AND P.PRODUCT_ID = S.PRODUCT_ID(+)
   AND S.WAREHOUSE_CD(+) = 'W01'
  WITH READ ONLY;

-- 시노님
CREATE OR REPLACE SYNONYM SYN_ORDER FOR SHOP.TB_ORDER;
CREATE PUBLIC SYNONYM SYN_CODE FOR SHOP.TB_CODE;
