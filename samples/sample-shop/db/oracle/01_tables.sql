-- =====================================================================
-- sample-shop 주문 관리 시스템 : 테이블 DDL (Oracle)
--   * PK/FK 일부는 CREATE TABLE 안에, 일부는 02_constraints_indexes.sql 의 ALTER TABLE 로 건다.
--   * TB_PAYMENT, TB_STOCK, TB_ORDER_HIST, TB_DAILY_SALES 는 일부러 FK 제약을 두지 않았다.
-- =====================================================================

-- 회원 등급
CREATE TABLE TB_MEMBER_GRADE (
    GRADE_CD       VARCHAR2(10)              NOT NULL,
    GRADE_NM       VARCHAR2(50)              NOT NULL,
    DISCOUNT_RATE  NUMBER(5,2)   DEFAULT 0   NOT NULL,
    CONSTRAINT PK_MEMBER_GRADE PRIMARY KEY (GRADE_CD)
);

-- 회원
CREATE TABLE TB_MEMBER (
    MEMBER_ID   NUMBER(12)                    NOT NULL,
    LOGIN_ID    VARCHAR2(30)                  NOT NULL,
    MEMBER_NM   VARCHAR2(100)                 NOT NULL,
    EMAIL       VARCHAR2(200),
    GRADE_CD    VARCHAR2(10)  DEFAULT 'NORMAL',
    STATUS_CD   CHAR(1)       DEFAULT 'A'     NOT NULL,
    POINT       NUMBER(10)    DEFAULT 0,
    JOIN_DT     DATE          DEFAULT SYSDATE NOT NULL,
    UPD_DT      DATE,
    CONSTRAINT PK_MEMBER PRIMARY KEY (MEMBER_ID),
    CONSTRAINT UK_MEMBER_LOGIN UNIQUE (LOGIN_ID)
);

-- 카테고리 (자기참조: 컬럼 수준 인라인 FK)
CREATE TABLE TB_CATEGORY (
    CATEGORY_ID  NUMBER(8)      NOT NULL PRIMARY KEY,
    PARENT_ID    NUMBER(8)      CONSTRAINT FK_CATEGORY_PARENT REFERENCES TB_CATEGORY (CATEGORY_ID),
    CATEGORY_NM  VARCHAR2(100)  NOT NULL,
    SORT_NO      NUMBER(4)      DEFAULT 0,
    USE_YN       CHAR(1)        DEFAULT 'Y' NOT NULL
);

-- 상품 (FK 는 ALTER TABLE 로)
CREATE TABLE TB_PRODUCT (
    PRODUCT_ID   NUMBER(12)                    NOT NULL,
    CATEGORY_ID  NUMBER(8)                     NOT NULL,
    PRODUCT_NM   VARCHAR2(200)                 NOT NULL,
    PRICE        NUMBER(12)     DEFAULT 0      NOT NULL,
    STATUS_CD    VARCHAR2(10)   DEFAULT 'SALE',
    REG_ID       VARCHAR2(30),
    REG_DT       DATE           DEFAULT SYSDATE,
    CONSTRAINT PK_PRODUCT PRIMARY KEY (PRODUCT_ID)
);

-- 재고 (FK 제약 없음: TB_PRODUCT 와의 관계는 조인으로만 알 수 있다)
CREATE TABLE TB_STOCK (
    PRODUCT_ID    NUMBER(12)                 NOT NULL,
    WAREHOUSE_CD  VARCHAR2(10) DEFAULT 'W01' NOT NULL,
    STOCK_QTY     NUMBER(10)   DEFAULT 0     NOT NULL,
    SAFE_QTY      NUMBER(10)   DEFAULT 0     NOT NULL,
    UPD_DT        DATE,
    CONSTRAINT PK_STOCK PRIMARY KEY (PRODUCT_ID, WAREHOUSE_CD)
);

-- 주문 (스키마를 붙여서 생성, 테이블 수준 FK)
CREATE TABLE SHOP.TB_ORDER (
    ORDER_ID      NUMBER(12)                    NOT NULL,
    MEMBER_ID     NUMBER(12)                    NOT NULL,
    ORDER_DT      VARCHAR2(8)                   NOT NULL,
    ORDER_STATUS  VARCHAR2(10)  DEFAULT '10'    NOT NULL,
    TOTAL_AMT     NUMBER(15,2)  DEFAULT 0       NOT NULL,
    CLOSE_YN      CHAR(1)       DEFAULT 'N'     NOT NULL,
    REG_ID        VARCHAR2(30),
    REG_DT        DATE          DEFAULT SYSDATE NOT NULL,
    UPD_ID        VARCHAR2(30),
    UPD_DT        DATE,
    CONSTRAINT PK_ORDER PRIMARY KEY (ORDER_ID),
    CONSTRAINT FK_ORDER_MEMBER FOREIGN KEY (MEMBER_ID) REFERENCES TB_MEMBER (MEMBER_ID)
) TABLESPACE TS_SHOP_DATA;

-- 주문 상세 (복합 PK, 주문 FK 는 여기서, 상품 FK 는 ALTER TABLE 로)
CREATE TABLE TB_ORDER_ITEM (
    ORDER_ID    NUMBER(12)             NOT NULL,
    ITEM_SEQ    NUMBER(4)              NOT NULL,
    PRODUCT_ID  NUMBER(12)             NOT NULL,
    QTY         NUMBER(8)    DEFAULT 1 NOT NULL,
    UNIT_PRICE  NUMBER(12)   DEFAULT 0 NOT NULL,
    AMT         NUMBER(15,2) DEFAULT 0 NOT NULL,
    CONSTRAINT PK_ORDER_ITEM PRIMARY KEY (ORDER_ID, ITEM_SEQ),
    CONSTRAINT FK_ORDER_ITEM_ORDER FOREIGN KEY (ORDER_ID)
        REFERENCES SHOP.TB_ORDER (ORDER_ID) ON DELETE CASCADE
);

-- 결제 (FK 제약 없음)
CREATE TABLE TB_PAYMENT (
    PAYMENT_ID     NUMBER(12)                   NOT NULL,
    ORDER_ID       NUMBER(12)                   NOT NULL,
    PAY_METHOD_CD  VARCHAR2(10),
    PAY_AMT        NUMBER(15,2) DEFAULT 0       NOT NULL,
    PAY_STATUS     VARCHAR2(10) DEFAULT 'READY' NOT NULL,
    PAY_DT         DATE,
    CONSTRAINT PK_PAYMENT PRIMARY KEY (PAYMENT_ID)
);

-- 배송 (FK 는 ALTER TABLE 로)
CREATE TABLE TB_DELIVERY (
    DELIVERY_ID      NUMBER(12)    NOT NULL,
    ORDER_ID         NUMBER(12)    NOT NULL,
    ADDR             VARCHAR2(400),
    DELIVERY_STATUS  VARCHAR2(10)  DEFAULT 'READY',
    INVOICE_NO       VARCHAR2(30),
    SHIP_DT          DATE,
    CONSTRAINT PK_DELIVERY PRIMARY KEY (DELIVERY_ID)
);

-- 공통 코드 (복합 PK)
CREATE TABLE SHOP.TB_CODE (
    GROUP_CD  VARCHAR2(30)  NOT NULL,
    CODE      VARCHAR2(10)  NOT NULL,
    CODE_NM   VARCHAR2(100) NOT NULL,
    SORT_NO   NUMBER(4)     DEFAULT 0,
    USE_YN    CHAR(1)       DEFAULT 'Y' NOT NULL,
    CONSTRAINT PK_CODE PRIMARY KEY (GROUP_CD, CODE)
);

-- 주문 상태 변경 이력 (FK 제약 없음)
CREATE TABLE TB_ORDER_HIST (
    HIST_ID       NUMBER(15)   NOT NULL,
    ORDER_ID      NUMBER(12)   NOT NULL,
    ORDER_STATUS  VARCHAR2(10) NOT NULL,
    CHG_DT        DATE         DEFAULT SYSDATE NOT NULL,
    CHG_ID        VARCHAR2(30),
    CONSTRAINT PK_ORDER_HIST PRIMARY KEY (HIST_ID)
);

-- 일 매출 집계 (배치가 적재, FK 제약 없음)
CREATE TABLE TB_DAILY_SALES (
    SALES_DT    VARCHAR2(8)            NOT NULL,
    PRODUCT_ID  NUMBER(12)             NOT NULL,
    SALES_QTY   NUMBER(12)   DEFAULT 0 NOT NULL,
    SALES_AMT   NUMBER(18,2) DEFAULT 0 NOT NULL,
    REG_DT      DATE         DEFAULT SYSDATE,
    CONSTRAINT PK_DAILY_SALES PRIMARY KEY (SALES_DT, PRODUCT_ID)
);

