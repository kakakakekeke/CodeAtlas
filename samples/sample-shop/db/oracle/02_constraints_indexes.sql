ALTER TABLE TB_MEMBER
    ADD CONSTRAINT FK_MEMBER_GRADE FOREIGN KEY (GRADE_CD)
    REFERENCES TB_MEMBER_GRADE (GRADE_CD);

ALTER TABLE TB_PRODUCT ADD CONSTRAINT FK_PRODUCT_CATEGORY
    FOREIGN KEY (CATEGORY_ID) REFERENCES TB_CATEGORY (CATEGORY_ID);

ALTER TABLE TB_ORDER_ITEM ADD (
    CONSTRAINT FK_ORDER_ITEM_PRODUCT FOREIGN KEY (PRODUCT_ID) REFERENCES TB_PRODUCT (PRODUCT_ID)
);

ALTER TABLE TB_DELIVERY
    ADD CONSTRAINT FK_DELIVERY_ORDER FOREIGN KEY (ORDER_ID)
    REFERENCES SHOP.TB_ORDER (ORDER_ID)
    ON DELETE CASCADE;

-- 체크 제약 (FK 아님)
ALTER TABLE TB_ORDER ADD CONSTRAINT CK_ORDER_CLOSE_YN CHECK (CLOSE_YN IN ('Y', 'N'));

